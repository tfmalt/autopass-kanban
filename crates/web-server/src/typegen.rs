const GENERATED_PATH: &str = "../../web/shared/generated/api.ts";
const SPRINT_STATUSES: [&str; 4] = ["planned", "active", "closed", "cancelled"];

fn generated_api_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED_PATH)
}

fn ts_config() -> Config {
    Config::new().with_large_int("number")
}

fn render_union(name: &str, values: &[&str]) -> String {
    let mut out = format!("export type {name} =\n");
    for (index, value) in values.iter().enumerate() {
        let suffix = if index + 1 == values.len() {
            ";\n\n"
        } else {
            "\n"
        };
        out.push_str(&format!("  | \"{value}\"{suffix}"));
    }
    out
}

fn render_array(name: &str, ty: &str, values: &[&str]) -> String {
    let body = values
        .iter()
        .map(|value| format!("\"{value}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!("export const {name}: {ty}[] = [{body}];\n\n")
}

