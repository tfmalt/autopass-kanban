fn export_declaration(declaration: String) -> String {
    if let Some(rest) = declaration.strip_prefix("type ") {
        format!("export type {rest}")
    } else if let Some(rest) = declaration.strip_prefix("interface ") {
        format!("export interface {rest}")
    } else {
        declaration
    }
}

fn render_generated_api() -> String {
    let cfg = ts_config();
    let mut out = String::from(
        "// Generated by `cargo test -p kanban-web-server export_bindings -- --exact`.\n// Do not edit by hand.\n\n",
    );
    out.push_str(&render_union(
        "StoryStatus",
        &kanban_core::SPRINT_STATUS_DISPLAY_ORDER,
    ));
    out.push_str(&render_array(
        "STORY_STATUSES",
        "StoryStatus",
        &kanban_core::SPRINT_STATUS_DISPLAY_ORDER,
    ));
    out.push_str(&render_union(
        "StoryLifecycleStatus",
        &kanban_core::CANONICAL_STORY_STATUSES,
    ));
    out.push_str(&render_array(
        "STORY_LIFECYCLE_STATUSES",
        "StoryLifecycleStatus",
        &kanban_core::CANONICAL_STORY_STATUSES,
    ));
    out.push_str(&render_union("SprintStatus", &SPRINT_STATUSES));
    out.push_str(&render_array(
        "SPRINT_STATUSES",
        "SprintStatus",
        &SPRINT_STATUSES,
    ));
    out.push_str(&render_union(
        "TaskStatus",
        &kanban_core::CANONICAL_TASK_STATUSES,
    ));
    out.push_str(&render_array(
        "TASK_STATUSES",
        "TaskStatus",
        &kanban_core::CANONICAL_TASK_STATUSES,
    ));
    for declaration in generated_declarations(&cfg) {
        out.push_str(&declaration);
        out.push_str("\n\n");
    }
    out
}

fn write_generated_api(path: &Path) -> Result<()> {
    let content = render_generated_api();
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).with_context(|| {
            format!("create generated TypeScript directory {}", parent.display())
        })?;
    }
    fs::write(path, content)
        .with_context(|| format!("write generated TypeScript bindings to {}", path.display()))
}

#[cfg(test)]
fn typegen_test_lock() -> &'static std::sync::Mutex<()> {
    static LOCK: std::sync::OnceLock<std::sync::Mutex<()>> = std::sync::OnceLock::new();
    LOCK.get_or_init(|| std::sync::Mutex::new(()))
}

#[test]
fn export_bindings() -> Result<()> {
    let _guard = typegen_test_lock().lock().unwrap();
    write_generated_api(&generated_api_path())
}

#[test]
fn generated_bindings_are_current() -> Result<()> {
    let _guard = typegen_test_lock().lock().unwrap();
    let path = generated_api_path();
    let expected = render_generated_api();
    let current = fs::read_to_string(&path)
        .with_context(|| format!("read generated TypeScript bindings from {}", path.display()))?;
    assert_eq!(current, expected, "{} is out of date", path.display());
    Ok(())
}
